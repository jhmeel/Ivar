"""Regenerates deploy/envoy/envoy.yaml from deploy/local/envoy_config.py.

The local stack and this reference config share one generator, so the
reference is exactly what the smoke test runs, with secrets replaced by
placeholders and the clusters pointed at DNS names.

    python3 deploy/envoy/generate.py deploy/local/.state
"""
import json
import os
import subprocess
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
state = sys.argv[1]
out = subprocess.run([sys.executable, os.path.join(HERE, "..", "local", "envoy_config.py"), state],
                     capture_output=True, text=True, env={**os.environ, "CORAZA_WASM": "1"}, check=True).stdout
cfg = json.loads(out)
for f in cfg["static_resources"]["listeners"][0]["filter_chains"][0]["filters"][0]["typed_config"]["http_filters"]:
    c = f.get("typed_config", {}).get("config")
    if not c:
        continue
    if f["name"] == "ivar":
        edge = json.loads(c["configuration"]["value"])
        edge.update({
            "sensor_id": "edge-1",
            "mode": "observe",
            "redaction_key_hex": "REPLACE_WITH_REDACTION_KEY_HEX",
            "keyring": {"keys": {
                "policy-a": [{"key_id": "policy-a", "alg": "ed25519", "bytes": "REPLACE_WITH_POLICY_A_PUBLIC_HEX"}, ["policy"]],
                "policy-b": [{"key_id": "policy-b", "alg": "ed25519", "bytes": "REPLACE_WITH_POLICY_B_PUBLIC_HEX"}, ["policy"]],
            }},
            "policy_bundle_base64": "",
        })
        c["configuration"]["value"] = json.dumps(edge)
        c["vm_config"]["code"]["local"]["filename"] = "/etc/envoy/ivar_edge_filter.wasm"
    if f["name"] == "coraza":
        c["vm_config"]["code"]["local"]["filename"] = "/etc/envoy/coraza-proxy-wasm.wasm"
for listener in cfg["static_resources"]["listeners"]:
    listener["address"]["socket_address"]["address"] = "0.0.0.0"
hosts = {"app": "app", "ivar_core": "ivar-core", "ivar_control": "ivar-control"}
for c in cfg["static_resources"]["clusters"]:
    c["type"] = "STRICT_DNS"
    c["load_assignment"]["endpoints"][0]["lb_endpoints"][0]["endpoint"]["address"]["socket_address"]["address"] = hosts[c["name"]]

header = """# Envoy at the edge with Coraza and the OWASP Core Rule Set ahead of the IVAR
# filter (sections 7.2 and 8). The IVAR filter starts from no policy and
# fetches a signed bundle from ivar-control; until one verifies, admin routes
# fail closed and other routes pass within the fail open budget. Replace the
# REPLACE_WITH values with your policy keyring and redaction key, and set
# "mode" to enforce only after the observe phase exit test passes.
#
# Generated by deploy/envoy/generate.py and checked with envoy --mode validate.
"""
with open(os.path.join(HERE, "envoy.yaml"), "w") as f:
    f.write(header + yaml.safe_dump(cfg, sort_keys=False, width=1000))
