#!/usr/bin/env bash
# Build the decision core to WebAssembly and generate bindings for Node
# (application SDKs) and the browser (replay viewer).
set -euo pipefail
cd "$(dirname "$0")/.."
# Reproducible output: no absolute build paths end up in the modules, so the
# copies committed for the Go and Python SDKs can be checked against a fresh
# build anywhere (CI fails when they differ).
target_dir="${CARGO_TARGET_DIR:-$PWD/target}"
# rustc applies the last matching prefix, so the target directory maps the
# same way whether or not it sits inside the checkout.
export RUSTFLAGS="${RUSTFLAGS:-} --remap-path-prefix=$PWD=/ivar --remap-path-prefix=${CARGO_HOME:-$HOME/.cargo}=/cargo --remap-path-prefix=$target_dir=/target"
cargo build --locked -p ivar-wasm --target wasm32-unknown-unknown --release
WASM="$target_dir/wasm32-unknown-unknown/release/ivar_wasm.wasm"
wasm-bindgen --target nodejs --out-dir sdk/node/core-wasm "$WASM"
# The generated folder is build output, so its package manifest is written
# here rather than kept in git.
cat > sdk/node/core-wasm/package.json <<'JSON'
{
  "name": "@ivar/core-wasm",
  "version": "0.1.0",
  "description": "The IVAR decision core compiled to WebAssembly (generated by scripts/build-wasm.sh)",
  "main": "ivar_wasm.js",
  "types": "ivar_wasm.d.ts",
  "files": ["ivar_wasm.js", "ivar_wasm.d.ts", "ivar_wasm_bg.wasm", "ivar_wasm_bg.wasm.d.ts", "snippets"],
  "license": "Apache-2.0"
}
JSON
wasm-bindgen --target web --out-dir replay-viewer/pkg "$WASM"
# The C ABI module for every other WebAssembly runtime.
cargo build --locked -p ivar-abi --target wasm32-wasip1 --release
ABI="$target_dir/wasm32-wasip1/release/ivar_abi.wasm"
mkdir -p sdk/python/ivar/_wasm sdk/go/wasm sdk/php/wasm sdk/java/src/main/resources sdk/dotnet/Ivar/wasm
for d in sdk/python/ivar/_wasm sdk/go/wasm sdk/php/wasm sdk/java/src/main/resources sdk/dotnet/Ivar/wasm; do
  cp "$ABI" "$d/ivar_core.wasm"
done
echo "built $(du -h "$WASM" | cut -f1) core"
